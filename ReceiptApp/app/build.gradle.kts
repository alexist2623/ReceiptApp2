fun gitCommitSha(): String {
    return runCatching {
        providers.exec {
            commandLine("git", "rev-parse", "--short=12", "HEAD")
        }.standardOutput.asText.get().trim()
    }.getOrElse { "unknown" }.ifBlank { "unknown" }
}

